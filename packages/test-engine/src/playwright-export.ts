import type { AssertionSpec, GeneratedTestCase, SelectorMeta, TestStep } from '@auditor/shared';

/**
 * Turns generated test cases into a plain Playwright Test spec that a team can
 * commit to its own repository and run with `npx playwright test`.
 *
 * Locators follow the same priority order as the runner (`locatorFromSelectors`)
 * so an exported test targets exactly the element the audit discovered.
 * Credentials are never written into the file: they are read from
 * TESTCREW_USERNAME / TESTCREW_PASSWORD at run time.
 */
export interface ExportOptions {
  baseUrl: string;
  projectName?: string;
  runId?: string;
  generatedAt?: Date;
}

export function exportPlaywrightSpec(tests: GeneratedTestCase[], options: ExportOptions): string {
  const lines: string[] = [];
  const stamp = (options.generatedAt ?? new Date()).toISOString();
  lines.push('// Generated by TestCrew AI App Auditor. Safe to edit and commit.');
  lines.push(`// Project: ${sanitizeComment(options.projectName ?? 'unknown')}`);
  if (options.runId) {
    lines.push(`// Source run: ${sanitizeComment(options.runId)}`);
  }
  lines.push(`// Generated: ${stamp}`);
  lines.push('//');
  lines.push('// Run with: npx playwright test');
  lines.push('// Credentials come from TESTCREW_USERNAME and TESTCREW_PASSWORD; set TESTCREW_BASE_URL to');
  lines.push('// point the suite at another environment (for example a preview deployment).');
  lines.push("import { expect, test, type Page } from '@playwright/test';");
  lines.push('');
  lines.push(`const BASE_URL = process.env.TESTCREW_BASE_URL ?? ${q(trimSlash(options.baseUrl))};`);
  lines.push("const USERNAME = process.env.TESTCREW_USERNAME ?? '';");
  lines.push("const PASSWORD = process.env.TESTCREW_PASSWORD ?? '';");
  lines.push('');
  lines.push('function url(target: string): string {');
  lines.push(`  const original = ${q(trimSlash(options.baseUrl))};`);
  lines.push('  if (target.startsWith(original)) return BASE_URL + target.slice(original.length);');
  lines.push("  if (target.startsWith('/')) return BASE_URL + target;");
  lines.push('  return target;');
  lines.push('}');
  lines.push('');
  lines.push('async function pageErrors(page: Page): Promise<string[]> {');
  lines.push('  return page.evaluate(() => ((window as unknown as { __testcrewErrors?: string[] }).__testcrewErrors ?? []));');
  lines.push('}');
  lines.push('');
  lines.push('test.beforeEach(async ({ page }) => {');
  lines.push('  await page.addInitScript(() => {');
  lines.push('    const store: string[] = [];');
  lines.push('    (window as unknown as { __testcrewErrors: string[] }).__testcrewErrors = store;');
  lines.push("    window.addEventListener('error', (event) => store.push(String(event.message)));");
  lines.push('  });');
  lines.push('});');
  lines.push('');

  const usedNames = new Set<string>();
  for (const testCase of tests) {
    let name = testCase.name;
    let suffix = 2;
    while (usedNames.has(name)) {
      name = `${testCase.name} (${suffix})`;
      suffix += 1;
    }
    usedNames.add(name);
    lines.push(...exportTest(testCase, name));
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function exportTest(testCase: GeneratedTestCase, name: string): string[] {
  const out: string[] = [];
  const tag = `[${testCase.category.toLowerCase()}]`;
  out.push(`test(${q(`${name} ${tag}`)}, async ({ page }) => {`);
  for (const line of wrapComment(testCase.description)) {
    out.push(`  // ${line}`);
  }
  if (testCase.viewport === 'mobile') {
    out.push('  await page.setViewportSize({ width: 390, height: 844 });');
  } else if (testCase.viewport === 'tablet') {
    out.push('  await page.setViewportSize({ width: 768, height: 1024 });');
  }
  out.push('  const vars: Record<string, string> = {};');
  out.push('  void vars;');
  for (const step of testCase.steps) {
    out.push(`  // ${sanitizeComment(step.description)}`);
    out.push(...exportStep(step).map((line) => `  ${line}`));
  }
  out.push('});');
  return out;
}

function exportStep(step: TestStep): string[] {
  const value = valueExpr(step.value);
  switch (step.type) {
    case 'navigate':
      return [`await page.goto(url(${q(step.href ?? step.value ?? '/')}));`];
    case 'reload':
      return ['await page.reload();'];
    case 'back':
      return ['await page.goBack();'];
    case 'wait':
      return step.selectors
        ? [`await ${locator(step.selectors)}.first().waitFor();`]
        : [`await page.waitForTimeout(${Math.min(step.timeoutMs ?? 1000, 2000)});`];
    case 'click':
      return [`await ${locator(requireSelectors(step))}.first().click();`];
    case 'type':
      return [`await ${locator(requireSelectors(step))}.first().fill(${value});`];
    case 'select':
      return [`await ${locator(requireSelectors(step))}.first().selectOption(${step.value ? value : '{ index: 0 }'});`];
    case 'upload':
      return [`await ${locator(requireSelectors(step))}.first().setInputFiles(${value});`];
    case 'capture':
      return [captureLine(step)];
    case 'assert':
      return step.assertion ? assertionLines(step.assertion) : [];
    default:
      return [`// Unsupported step type ${String(step.type)}`];
  }
}

function captureLine(step: TestStep): string {
  const key = q(step.captureAs ?? 'value');
  if (!step.selectors) {
    return `vars[${key}] = await page.title();`;
  }
  if (step.captureMode === 'count') {
    return `vars[${key}] = String(await ${locator(step.selectors)}.count());`;
  }
  return `vars[${key}] = ((await ${locator(step.selectors)}.first().textContent()) ?? '').trim();`;
}

function assertionLines(spec: AssertionSpec): string[] {
  const operator = spec.operator;
  const expected = expectedExpr(spec.expected);
  const target = spec.selectors ? `${locator(spec.selectors)}.first()` : null;
  switch (spec.kind) {
    case 'url':
      return [urlAssertion(operator ?? 'contains', spec.expected)];
    case 'text':
      if (operator === 'absent') return [`await expect(page.locator('body')).not.toContainText(${expected});`];
      if (operator === 'matches') return [`await expect(page.locator('body')).toContainText(new RegExp(${expected}));`];
      return [`await expect(page.locator('body')).toContainText(${expected});`];
    case 'element_text':
      if (!target) return ['// element_text assertion without a selector was skipped'];
      if (operator === 'equals') return [`await expect(${target}).toHaveText(${expected});`];
      if (operator === 'absent') return [`await expect(${target}).not.toContainText(${expected});`];
      if (operator === 'matches') return [`await expect(${target}).toHaveText(new RegExp(${expected}));`];
      if (operator === 'gte' || operator === 'lte') {
        const cmp = operator === 'gte' ? 'toBeGreaterThanOrEqual' : 'toBeLessThanOrEqual';
        return [`expect(Number(((await ${target}.textContent()) ?? '').replace(/[^0-9.-]/g, ''))).${cmp}(Number(${expected}));`];
      }
      return [`await expect(${target}).toContainText(${expected});`];
    case 'visibility':
      if (!target) return [];
      return [operator === 'absent' ? `await expect(${target}).toBeHidden();` : `await expect(${target}).toBeVisible();`];
    case 'existence':
      if (!spec.selectors) return [];
      return [
        operator === 'absent'
          ? `await expect(${locator(spec.selectors)}).toHaveCount(0);`
          : `expect(await ${locator(spec.selectors)}.count()).toBeGreaterThan(0);`,
      ];
    case 'value':
      if (!target) return [];
      return operator === 'equals'
        ? [`await expect(${target}).toHaveValue(${expected});`]
        : [`expect(await ${target}.inputValue()).toContain(${expected});`];
    case 'attribute':
      if (!target || !spec.attribute) return [];
      return [`await expect(${target}).toHaveAttribute(${q(spec.attribute)}, ${expected});`];
    case 'count': {
      if (!spec.selectors) return [];
      const count = `await ${locator(spec.selectors)}.count()`;
      if (operator === 'gte') return [`expect(${count}).toBeGreaterThanOrEqual(Number(${expected}));`];
      if (operator === 'lte') return [`expect(${count}).toBeLessThanOrEqual(Number(${expected}));`];
      return [`expect(${count}).toBe(Number(${expected}));`];
    }
    case 'http':
      return [`// HTTP ${spec.statusCode ?? spec.expected ?? 500} responses are checked by the TestCrew runner; add a page.on('response') listener to enforce it here.`];
    case 'console_error':
    case 'page_error':
      return ['expect(await pageErrors(page)).toEqual([]);'];
    default:
      return [`// Unsupported assertion ${String(spec.kind)}`];
  }
}

function urlAssertion(operator: string, expected: AssertionSpec['expected']): string {
  const text = String(expected ?? '');
  if (operator === 'matches') {
    return `await expect(page).toHaveURL(new RegExp(${q(text)}));`;
  }
  if (operator === 'equals') {
    return `await expect(page).toHaveURL(url(${q(text)}));`;
  }
  if (operator === 'absent') {
    return `expect(page.url()).not.toContain(${q(text)});`;
  }
  return `await expect(page).toHaveURL(new RegExp(${q(escapeRegExp(text))}));`;
}

export function locator(selectors: SelectorMeta): string {
  if (selectors.testId) {
    return `page.getByTestId(${q(selectors.testId)})`;
  }
  if (selectors.id) {
    return `page.locator(${q(`#${cssEscapeId(selectors.id)}`)})`;
  }
  if (selectors.role && selectors.accessibleName) {
    return `page.getByRole(${q(selectors.role)}, { name: ${q(selectors.accessibleName)} })`;
  }
  if (selectors.label) {
    return `page.getByLabel(${q(selectors.label)})`;
  }
  if (selectors.name) {
    return `page.locator(${q(`[name="${selectors.name.replace(/"/g, '\\"')}"]`)})`;
  }
  if (selectors.text) {
    return `page.getByText(${q(selectors.text)}, { exact: ${selectors.text.length <= 48} })`;
  }
  return `page.locator(${q(selectors.css ?? selectors.primary)})`;
}

function requireSelectors(step: TestStep): SelectorMeta {
  if (!step.selectors) {
    throw new Error(`Step "${step.description}" has no discovered selector and cannot be exported`);
  }
  return step.selectors;
}

/** Template values: credentials map to env vars, {{var}} / {{var+1}} map to captured values. */
function valueExpr(value: string | undefined): string {
  if (value === undefined) {
    return "''";
  }
  if (value === '{{credential.username}}') return 'USERNAME';
  if (value === '{{credential.password}}') return 'PASSWORD';
  return expectedExpr(value);
}

function expectedExpr(value: AssertionSpec['expected']): string {
  if (value === undefined) {
    return "''";
  }
  if (typeof value !== 'string') {
    return JSON.stringify(String(value));
  }
  const template = /\{\{\s*([a-zA-Z_][\w]*)\s*(?:([+-])\s*(\d+(?:\.\d+)?))?\s*\}\}/g;
  if (!template.test(value)) {
    return q(value);
  }
  template.lastIndex = 0;
  const parts: string[] = [];
  let last = 0;
  for (let match = template.exec(value); match; match = template.exec(value)) {
    if (match.index > last) parts.push(q(value.slice(last, match.index)));
    const [, name, sign, amount] = match;
    if (name === 'credential') {
      parts.push(q(match[0]));
    } else if (sign && amount) {
      parts.push(`String(Number(vars[${q(name ?? '')}]) ${sign} ${amount})`);
    } else {
      parts.push(`vars[${q(name ?? '')}]`);
    }
    last = match.index + match[0].length;
  }
  if (last < value.length) parts.push(q(value.slice(last)));
  return parts.join(' + ');
}

function q(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r/g, '\\r').replace(/\n/g, '\\n')}'`;
}

function trimSlash(value: string): string {
  return value.replace(/\/+$/, '');
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
}

function cssEscapeId(id: string): string {
  return id.replace(/([ !"#$%&'()*+,./:;<=>?@[\\\]^`{|}~])/g, '\\$1');
}

function sanitizeComment(value: string): string {
  return value.replace(/\*\//g, '* /').replace(/[\r\n]+/g, ' ');
}

function wrapComment(value: string): string[] {
  const words = sanitizeComment(value).split(/\s+/).filter(Boolean);
  const out: string[] = [];
  let current = '';
  for (const word of words) {
    if ((current + ' ' + word).trim().length > 96) {
      out.push(current.trim());
      current = word;
    } else {
      current = `${current} ${word}`;
    }
  }
  if (current.trim()) out.push(current.trim());
  return out;
}
